import { motion } from "framer-motion";
import { useAnimation } from "@/contexts/AnimationContext";
import { useLanguage } from "@/contexts/LanguageContext";

export default function AnimationToggle() {
  const { animationsEnabled, toggleAnimations } = useAnimation();
  const { t } = useLanguage();

  return (
    <motion.button
      onClick={toggleAnimations}
      className="fixed bottom-4 right-4 z-50 bg-fisher-blue text-white rounded-full p-2 shadow-lg"
      whileHover={{ scale: 1.05 }}
      whileTap={{ scale: 0.95 }}
      transition={{ type: "spring", stiffness: 400, damping: 17 }}
      aria-label={animationsEnabled ? t('animation.disable') : t('animation.enable')}
      title={animationsEnabled ? t('animation.disable') : t('animation.enable')}
    >
      {animationsEnabled ? (
        <svg xmlns="http://www.w3.org/2000/svg" className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M15 10l4.553-2.276A1 1 0 0121 8.618v6.764a1 1 0 01-1.447.894L15 14M5 18h8a2 2 0 002-2V8a2 2 0 00-2-2H5a2 2 0 00-2 2v8a2 2 0 002 2z" />
        </svg>
      ) : (
        <svg xmlns="http://www.w3.org/2000/svg" className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M15.536 8.464a5 5 0 010 7.072m2.828-9.9a9 9 0 010 12.728M5.586 15H4a1 1 0 01-1-1v-4a1 1 0 011-1h1.586l4.707-4.707C10.923 3.663 12 4.109 12 5v14c0 .891-1.077 1.337-1.707.707L5.586 15z" />
        </svg>
      )}
    </motion.button>
  );
}