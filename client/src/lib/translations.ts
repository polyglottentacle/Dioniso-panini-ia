// Translate function to use with the context
export function translate(key: string, language: Language, params?: Record<string, string | number>): string {
  // Get the translation for the key in the specified language, or fallback to English if not found
  const translation = translations[language]?.[key] || translations['en'][key] || key;
  
  // If there are parameters to replace, replace them in the translation
  if (params) {
    return Object.entries(params).reduce((result, [param, value]) => {
      return result.replace(new RegExp(`{${param}}`, 'g'), String(value));
    }, translation);
  }
  
  return translation;
}